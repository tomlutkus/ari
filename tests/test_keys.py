# The version 2 upgrade


V2 = {
    "version": 2,
    "defaults": {"user": "deploy", "ssh_key": "~/.ssh/lab-ed25519"},
    "hosts": [
        {"name": "a", "hostname": "192.0.2.1", "ssh_key": "~/.ssh/old/id_rsa"},
        {"name": "b", "hostname": "192.0.2.2", "ssh_key": "~/.ssh/new/id_rsa"},
        {"name": "c", "hostname": "192.0.2.3", "ssh_key": "~/.ssh/old/id_rsa"},
        {"name": "d", "hostname": "192.0.2.4", "ssh_key": ""},
        {"name": "e", "hostname": "192.0.2.5"},
    ],
}


def test_version_2_declares_each_path_once_defaults_first(tmp_path):
    inventory = load(tmp_path, V2)
    assert inventory.keys == {
        "lab-ed25519": KeyDef("~/.ssh/lab-ed25519"),
        "id_rsa": KeyDef("~/.ssh/old/id_rsa"),
        "id_rsa-2": KeyDef("~/.ssh/new/id_rsa"),
    }
    assert inventory.defaults.keys == ["lab-ed25519"]
    assert [h.keys for h in inventory.hosts] == [["id_rsa"], ["id_rsa-2"], ["id_rsa"], [], []]
    assert [inventory.identity_files(h) for h in inventory.hosts][-2:] == [["~/.ssh/lab-ed25519"]] * 2


def test_version_2_saves_as_version_3(tmp_path):
    inventory = load(tmp_path, V2)
    storage.save(inventory)
    saved = json.loads((tmp_path / "personal.json").read_text())
    assert saved["version"] == 3
    assert list(saved)[:5] == ["version", "last_updated", "defaults", "keys", "groups"]
    assert "ssh_key" not in json.dumps(saved)
    assert saved["keys"]["id_rsa-2"] == {"path": "~/.ssh/new/id_rsa"}
    assert storage.load(InventoryConfig("personal", tmp_path / "personal.json")).to_dict() == inventory.to_dict()


