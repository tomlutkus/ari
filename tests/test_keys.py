def hand_edit(home, name, change, inventory="work"):
    content = data(home, inventory)
    if content["version"] == 2:
        content = storage.load(InventoryConfig(inventory, path_of(home, inventory))).to_dict()
    change(content)
    path_of(home, inventory).write_text(json.dumps(content))


def test_export_and_edit_refuse_an_undeclared_or_repeated_key(mixed, capsys):
    def change(content):
        content["hosts"][2]["keys"] = ["gone", "lab-ed25519", "lab-ed25519"]
        content["defaults"]["keys"] = ["missing"]

    hand_edit(mixed, "web-01", change)
    assert run("export") == 1
    err = capsys.readouterr().err
    assert "work: defaults: key 'missing' isn't declared" in err
    assert "work (web-01): key 'lab-ed25519' is listed twice" in err
    assert "work (web-01): key 'gone' isn't declared" in err
    assert not (mixed / "ssh" / "20-work.conf").exists()
    assert run("edit", "web-01", "--notes", "x") == 1
    assert "key 'gone' isn't declared" in capsys.readouterr().err


