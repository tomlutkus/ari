"""Schema 3: keys are declared once per inventory and listed by name; ssh options ssh uses every
line of can hold a list. A version 2 file upgrades on read and exports the same bytes."""

import json

import pytest

from conftest import MIXED, write_config, write_mixed
from ari import storage
from ari.config import InventoryConfig
from ari.errors import HostsError
from ari.cli import main
from ari.models import Defaults, Host, Inventory, KeyDef, declare_key, key_name
from ari.modules.ssh import render


def run(*argv):
    return main(list(argv))


def path_of(home, name="personal"):
    return home / "config" / "ari" / f"{name}.json"


def data(home, name="personal"):
    return json.loads(path_of(home, name).read_text())


def stored(home, host, name="personal"):
    return next(h for h in data(home, name)["hosts"] if h["name"] == host)


def load(tmp_path, content):
    path = tmp_path / "personal.json"
    path.write_text(json.dumps(content) if not isinstance(content, str) else content)
    return storage.load(InventoryConfig("personal", path))


