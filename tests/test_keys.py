# Options that hold a list


def options_file(tmp_path, options):
    return {"version": 3, "hosts": [{"name": "a", "hostname": "192.0.2.1", "modules": {"ssh": {"options": options}}}]}


def test_listable_options_render_one_line_per_value(tmp_path):
    inventory = load(tmp_path, options_file(tmp_path, {
        "LocalForward": ["5432 localhost:5432", "8080 localhost:80"],
        "SendEnv": "LANG",
        "ProxyJump": "jump",
    }))
    assert render(inventory, inventory.hosts).splitlines()[4:] == [
        "    LocalForward 5432 localhost:5432",
        "    LocalForward 8080 localhost:80",
        "    SendEnv LANG",
        "    ProxyJump jump",
    ]


def test_a_list_of_one_is_stored_as_its_string(tmp_path):
    inventory = load(tmp_path, options_file(tmp_path, {"RemoteForward": ["9000 localhost:9000"]}))
    assert inventory.hosts[0].modules == {"ssh": {"options": {"RemoteForward": "9000 localhost:9000"}}}


@pytest.mark.parametrize(
    "options, message",
    [
        ({"ProxyJump": ["a", "b"]}, "option ProxyJump takes one value; ssh reads only the first"),
        ({"LocalForward": []}, "must be a string or a non-empty list of strings"),
        ({"DynamicForward": ["1080", 5]}, "must be a string or a non-empty list of strings"),
        ({"SendEnv": ["LANG", "LC_\n"]}, "option SendEnv must be one line"),
        ({"IdentityFile": "~/.ssh/k"}, "IdentityFile can't be an option; it's the keys field"),
    ],
)
def test_lists_only_where_ssh_uses_every_line(tmp_path, options, message):
    with pytest.raises(HostsError, match=message):
        load(tmp_path, options_file(tmp_path, options))


def test_show_and_search_see_every_value(home, capsys):
    write_config(home, MIXED)
    path_of(home).parent.mkdir(parents=True, exist_ok=True)
    path_of(home).write_text(json.dumps(options_file(None, {"LocalForward": ["5432 localhost:5432", "8080 localhost:80"]})))
    assert run("show", "a") == 0
