@pytest.mark.parametrize("outputs, message", ERRORS)
def test_settings_a_table_cant_use_stop_every_command(home, capsys, outputs, message):
    config_with(home, "\n" + outputs)
    with pytest.raises(HostsError) as refused:
        load_config()
    assert message in str(refused.value)
    assert run("export") == 1
    assert message in capsys.readouterr().err
    assert not any((home / "ssh").iterdir())


@pytest.mark.parametrize("mode, octal", [("0600", 0o600), ("644", 0o644), ("0664", 0o664), ("0700", 0o700)])
def test_a_mode_is_an_octal_string(home, mode, octal):
    config_with(home, f'\n[[inventories.work.table.outputs]]\npath = "~/hosts.md"\ncolumns = ["name"]\nmode = "{mode}"\n')
    (table,) = load_config().get("work").modules["table"].settings
    assert table.mode == octal and table.format == "md" and table.columns == ("name",)


def test_a_host_holds_no_table_data(tables, capsys):
    path = tables / "config" / "ari" / "work.json"
    data = json.loads(path.read_text())
    data["hosts"][0]["modules"] = {"table": {"columns": ["name"]}}
    path.write_text(json.dumps(data))
    assert run("ls") == 1
    assert "unknown keys ['columns']" in capsys.readouterr().err


def imported(path: Path) -> set[str]:
    """The ari modules a source file imports, as dotted names relative to the package."""
    names = set()
    for node in ast.walk(ast.parse(path.read_text())):
        if isinstance(node, ast.ImportFrom):
            base = ("." * node.level) + (node.module or "")
            names |= {base} | {f"{base}.{a.name}" if node.module else f"{base}{a.name}" for a in node.names}
        elif isinstance(node, ast.Import):
            names |= {a.name for a in node.names}
    return names


def test_modules_and_columns_never_import_core():
    """Core finds modules through the registry and reads columns; neither reaches back."""
    package = Path(ari.__file__).parent
    for path in [*sorted((package / "modules").glob("*.py")), package / "columns.py"]:
        found = imported(path)
        assert not {n for n in found if n.rstrip(".").endswith("core") or n == "ari.core"}, path.name
    assert imported(package / "modules" / "table.py") >= {"..columns", "..columns.COLUMNS"}
