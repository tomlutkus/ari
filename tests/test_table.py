TABLES = MIXED + """
[[inventories.personal.table.outputs]]
path = "SSH/docs/personal.txt"
format = "csv"
columns = ["name", "os"]
mode = "0600"

[[inventories.work.table.outputs]]
path = "SSH/docs/work.md"
columns = ["name", "hostname", "user", "keys", "os", "groups", "notes"]

[[inventories.work.table.outputs]]
path = "SSH/docs/work.csv"
columns = ["notes", "name", "port"]
"""

HEADER = "<!-- Generated by ari from work.json. Do not edit. -->\n\n"


def run(*argv):
    return main(list(argv))


@pytest.fixture
def tables(home):
    write_listed(home, TABLES)
    return home


def docs(home) -> dict[str, bytes]:
    return {p.name: p.read_bytes() for p in sorted((home / "ssh" / "docs").iterdir())}


def picture(home) -> dict[str, tuple[str, int]]:
    """Every generated file: its hash and mode."""
    return {
        str(p.relative_to(home)): (hashlib.sha256(p.read_bytes()).hexdigest(), stat.S_IMODE(p.stat().st_mode))
        for p in sorted((home / "ssh").rglob("*"))
        if p.is_file()
    }


def ls(capsys, *argv) -> str:
    capsys.readouterr()
    assert run("ls", *argv) == 0
    return capsys.readouterr().out


def test_each_output_is_what_ls_prints_for_its_columns(tables, capsys):
    assert run("export") == 0
    written = docs(tables)
    assert set(written) == {"personal.txt", "work.md", "work.csv"}
    md = ls(capsys, "-i", "work", "--format", "md", "--columns", "name,hostname,user,keys,os,groups,notes")
    assert written["work.md"].decode() == HEADER + md
    assert written["work.csv"].decode() == ls(capsys, "-i", "work", "--format", "csv", "--columns", "notes,name,port")
    assert written["personal.txt"].decode() == ls(capsys, "-i", "personal", "--format", "csv", "--columns", "name,os")
    assert written["personal.txt"] == b"name,os\nnas,TrueNAS 25.04\npi,Raspberry Pi OS 12\nscratch,\n"


def test_export_reports_each_table_and_a_second_export_changes_nothing(tables, capsys):
    assert run("export") == 0
    out = capsys.readouterr().out
    assert f"wrote {tables}/ssh/docs/work.md (work, table, 3 hosts)" in out
    assert f"wrote {tables}/ssh/docs/personal.txt (personal, table, 3 hosts)" in out
    before = picture(tables)
    assert run("export") == 0
    out = capsys.readouterr().out
    assert "wrote" not in out and out.count("unchanged") == len(before) == 8
    assert picture(tables) == before


def test_each_output_takes_its_own_mode(tables, capsys):
    assert run("export") == 0
    modes = {name: mode for name, (_, mode) in picture(tables).items() if "/docs/" in name}
    assert modes == {"ssh/docs/personal.txt": 0o600, "ssh/docs/work.csv": 0o644, "ssh/docs/work.md": 0o644}
    (tables / "ssh" / "docs" / "work.md").chmod(0o640)
    capsys.readouterr()
    assert run("export") == 0
    assert f"unchanged {tables}/ssh/docs/work.md (work, table, 3 hosts); mode set to 0644" in capsys.readouterr().out
    assert stat.S_IMODE((tables / "ssh" / "docs" / "work.md").stat().st_mode) == 0o644


def test_a_host_excluding_the_module_stays_out_of_every_table(tables, capsys):
    assert run("edit", "vault-01", "--exclude", "table") == 0
    assert run("export") == 0
    written = docs(tables)
    assert b"vault-01" not in written["work.md"] and b"vault-01" not in written["work.csv"]
    assert b"web-01" in written["work.md"]
    rows = {line.split()[0]: line.split() for line in ls(capsys, "--columns", "name,table").splitlines()[3:9]}
    assert rows["vault-01"][1] == "excluded" and rows["web-01"][1] == "✓"


def test_the_guard_refuses_a_hand_edit_until_forced(tables, capsys):
    assert run("export") == 0
    target = tables / "ssh" / "docs" / "work.md"
    target.write_text(target.read_text() + "a line by hand\n")
    edited = picture(tables)
    assert run("export") == 1
    assert "work.md: edited since the last export" in capsys.readouterr().err
    assert picture(tables) == edited
    assert run("export", "--force") == 0
    assert "a line by hand" not in target.read_text()


def test_re_importing_the_other_files_leaves_the_tables_as_they_were(tables, capsys):
    assert run("export") == 0
    before = picture(tables)
    assert run("import", "ssh", str(tables / "ssh" / "10-personal.conf"), "-i", "personal") == 0
    assert run("import", "ssh", str(tables / "ssh" / "20-work.conf"), "-i", "work") == 0
    assert run("import", "ansible", str(tables / "ssh" / "ansible"), "-i", "work") == 0
    capsys.readouterr()
    assert run("export") == 0
    assert "wrote" not in capsys.readouterr().out
    assert picture(tables) == before


def test_a_change_to_the_record_shows_in_the_tables_only_where_a_column_holds_it(tables, capsys):
    assert run("export") == 0
    before = docs(tables)
    assert run("edit", "web-01", "--os", "Debian 13") == 0
    capsys.readouterr()
    assert run("export") == 0
    said = {line.split()[1].rsplit("/", 1)[-1]: line.split()[0] for line in capsys.readouterr().out.splitlines()}
    assert said["work.md"] == "wrote" and said["work.csv"] == said["personal.txt"] == said["20-work.conf"] == "unchanged"
    after = docs(tables)
    assert after["work.csv"] == before["work.csv"] and after["personal.txt"] == before["personal.txt"]
    assert b"| web-01 | 192.0.2.10 | admin | lab | Debian 13 | zone_app | front door |" in after["work.md"]


def test_ls_has_a_table_column_once_an_inventory_turns_it_on(tables, capsys):
    assert core.export_modules(load_config()) == ["ssh", "table", "ansible"]
    assert ls(capsys, "--format", "csv").splitlines()[0] == "name,hostname,user,port,ssh,table,ansible,groups,inv"


def test_a_parked_table_writes_nothing_and_has_no_column(home, capsys):
    parked = TABLES
    for name in ("personal", "work"):
        head = f"[[inventories.{name}.table.outputs]]"
        parked = parked.replace(head, f"[inventories.{name}.table]\nenabled = false\n\n{head}", 1)
    write_listed(home, parked)
    assert run("export") == 0
    assert not (home / "ssh" / "docs").exists()
    assert "table" not in core.export_modules(load_config())


def test_it_doesnt_import(tables, capsys):
    assert run("import", "table", str(tables / "ssh" / "docs" / "work.md"), "-i", "work") == 1
    assert "the table module can't import" in capsys.readouterr().err


def test_a_table_sharing_a_path_with_another_target_writes_nothing(home, capsys):
    write_listed(home, MIXED + '\n[[inventories.personal.table.outputs]]\npath = "SSH/20-work.conf"\nformat = "md"\ncolumns = ["name"]\n')
    assert run("export") == 1
    assert "more than one target writes" in capsys.readouterr().err
    assert sorted(p.name for p in (home / "ssh").iterdir()) == []


def config_with(home, outputs: str) -> None:
    write_config(home, MIXED + outputs)


